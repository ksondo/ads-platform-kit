#!/usr/bin/env bash
# Provision separate restricted PostgreSQL logins for five NEW ADS demo databases.
# No app starts; migration owners are never used as app runtime connections.
set -Eeuo pipefail
umask 077
[[ $# == 1 ]] || { echo 'Usage: provision-five-demo-runtime-logins.sh --plan|--provision|--verify' >&2; exit 2; }
mode="$1"
case "$mode" in --plan|--provision|--verify) ;; *) exit 2;; esac
[[ "$(id -u)" == 0 && "$(hostname -s)" == vmi3191089 ]] || exit 2
here="$(cd "$(dirname "$0")" && pwd -P)"
dir=/etc/ads-demo/apps
[[ -d "$dir" && ! -L "$dir" ]] || exit 2
safe_file() { [[ -f "$1" && ! -L "$1" && "$(stat -c '%u:%a' "$1")" == 0:600 ]]; }
roles_for() {
  case "$1" in
    education)
      printf '%s\n' 'ads_education_api education_api API' \
       'ads_education_worker education_worker WORKER' \
       'ads_education_webhook education_payment_webhook WEBHOOK' ;;
    fleetguard) printf '%s\n' 'ads_fleetguard_api fleetguard_app API' ;;
    mamacare) printf '%s\n' 'ads_mamacare_api mamacare_app API' \
       'ads_mamacare_worker mamacare_job WORKER' ;;
    tontine) printf '%s\n' 'tontine_api tontine_app API' \
       'tontine_worker tontine_worker WORKER' \
       'tontine_webhook tontine_webhook WEBHOOK' ;;
    home-services) : ;;
    *) exit 2 ;;
  esac
}
verify_role() {
  local db="$1" owner="$2" name="$3" group="$4" result
  result="$(docker exec "$db" psql -X -qAt -U "$owner" -d "$database" -v ON_ERROR_STOP=1 -c "
    SELECT CASE WHEN
     r.rolcanlogin AND NOT r.rolsuper AND NOT r.rolbypassrls AND
     NOT r.rolcreaterole AND NOT r.rolcreatedb AND NOT r.rolreplication AND
     NOT EXISTS(SELECT 1 FROM pg_class c WHERE c.relowner=r.oid) AND
     NOT EXISTS(SELECT 1 FROM pg_database d WHERE d.datdba=r.oid) AND
     pg_has_role(r.rolname, '$group', 'MEMBER') AND
     (SELECT count(*) FROM pg_auth_members m WHERE m.member=r.oid)=1 AND
     (SELECT count(*) FROM pg_auth_members m JOIN pg_roles p ON p.oid=m.roleid
      WHERE m.member=r.oid AND p.rolname='$group')=1
     THEN 'PASS' ELSE 'FAIL' END
     FROM pg_roles r WHERE r.rolname='$name';")"
  [[ "$result" == PASS ]] || { echo "ROLE_VERIFICATION_FAILED login=$name" >&2; return 1; }
  echo "RUNTIME_ROLE_PASS login=$name membership=$group"
}
verify_home() {
  local result
  result="$(docker exec "$container" psql -X -qAt -U "$POSTGRES_USER" -d "$database" -v ON_ERROR_STOP=1 -c "
   SELECT CASE WHEN r.rolcanlogin AND NOT r.rolsuper AND NOT r.rolbypassrls AND
    NOT r.rolcreaterole AND NOT r.rolcreatedb AND
    NOT EXISTS(SELECT 1 FROM pg_auth_members m WHERE m.member=r.oid) AND
    NOT EXISTS(SELECT 1 FROM pg_class c WHERE c.relowner=r.oid)
    THEN 'PASS' ELSE 'FAIL' END FROM pg_roles r WHERE r.rolname='home_runtime';")"
  [[ "$result" == PASS ]] || { echo 'HOME_RUNTIME_LOGIN_REFUSED' >&2; return 1; }
  echo 'RUNTIME_ROLE_PASS login=home_runtime membership=direct-grants'
}
if [[ "$mode" == --provision ]]; then
  exec 9>/var/lock/ads-new-demo-schema-migrate.lock
  flock -n 9 || { echo 'REFUSED: schema migration in progress' >&2; exit 2; }
fi
# All schema and RLS gates must pass before creating a single login.
for app in education fleetguard home-services mamacare tontine; do
  bash "$here/migrate-five-demo-schemas.sh" --verify "$app" >/dev/null || {
    echo "REFUSED: migration verification failed for $app" >&2; exit 2;
  }
done
echo "ADS_ALL_FIVE_SCHEMAS=VERIFIED mode=$mode"
for app in education fleetguard home-services mamacare tontine; do
  suffix="$(printf %s "$app" | tr '-' '_')"
  container="ads-demo-$app-db"
  database="ads_demo_$suffix"
  owner="ads_demo_""$suffix""_owner"
  db_file="$dir/$app-db.env"
  connections="$dir/$app-connections.env"
  password_file="$dir/$app-restricted-logins.env"
  safe_file "$db_file" || { echo "MISSING_PROTECTED_DB_FILE app=$app" >&2; exit 2; }
  # Only trusted root-owned credentials generated by our DB bootstrap.
  source "$db_file"
  [[ "$POSTGRES_DB" == "$database" && "$POSTGRES_USER" == "$owner" &&
     "$POSTGRES_PASSWORD" =~ ^[a-f0-9]{64}$ ]] || exit 2
  [[ "$(docker inspect -f '{{index .Config.Labels "com.ads.demo.app"}}' "$container")" == "$app" ]] || exit 2
  [[ "$(docker inspect -f '{{.State.Health.Status}}' "$container")" == healthy ]] || exit 2

  if [[ "$mode" == --plan ]]; then
    if [[ "$app" == home-services ]]; then
      echo 'RUNTIME_PLAN app=home-services login=home_runtime (existing)'
    else
      roles_for "$app" | while read -r login group kind; do
        echo "RUNTIME_PLAN app=$app login=$login group=$group"
      done
    fi
    continue
  fi

  if [[ "$app" == home-services ]]; then
    home_file="$dir/home-services-runtime-bootstrap.env"
    safe_file "$home_file" || { echo 'MISSING_HOME_RUNTIME_BOOTSTRAP' >&2; exit 2; }
    source "$home_file"
    [[ "$HOME_RUNTIME_ROLE" == home_runtime && "$HOME_RUNTIME_PASSWORD" =~ ^[a-f0-9]{64}$ ]] || exit 2
    verify_home
    if [[ "$mode" == --provision ]]; then
      [[ ! -L "$connections" ]] || exit 2
      tmp="$(mktemp "$dir/.connections-home-XXXXXXXX")"
      printf 'DATABASE_URL=postgresql://home_runtime:%s@%s:5432/%s\n' \
        "$HOME_RUNTIME_PASSWORD" "$container" "$database" > "$tmp"
      chmod 0600 "$tmp"
      mv -f -- "$tmp" "$connections"
    else
      safe_file "$connections" || exit 1
    fi
    echo 'APP_RUNTIME_READY app=home-services'
    unset HOME_RUNTIME_PASSWORD HOME_RUNTIME_ROLE POSTGRES_PASSWORD
    continue
  fi

  if [[ "$mode" == --provision && ! -e "$password_file" && ! -L "$password_file" ]]; then
    # On first provision never adopt unknown existing SQL logins.
    while read -r login group kind; do
      [[ -z "$(docker exec "$container" psql -X -qAt -U "$owner" -d "$database" -c \
        "SELECT rolname FROM pg_roles WHERE rolname='$login'")" ]] || {
          echo "REFUSED_EXISTING_UNTRACKED_LOGIN $login" >&2; exit 2;
        }
    done < <(roles_for "$app")
    tmp="$(mktemp "$dir/.restricted-$app-XXXXXXXX")"
    printf 'API_PASSWORD=%s\nWORKER_PASSWORD=%s\nWEBHOOK_PASSWORD=%s\n' \
      "$(openssl rand -hex 32)" "$(openssl rand -hex 32)" "$(openssl rand -hex 32)" > "$tmp"
    chmod 0600 "$tmp"
    mv -- "$tmp" "$password_file"
  fi
  safe_file "$password_file" || { echo "MISSING_RESTRICTED_PASSWORDS app=$app" >&2; exit 2; }
  source "$password_file"
  for value in "$API_PASSWORD" "$WORKER_PASSWORD" "$WEBHOOK_PASSWORD"; do
    [[ "$value" =~ ^[a-f0-9]{64}$ ]] || exit 2
  done
  if [[ "$mode" == --provision ]]; then
    # SQL and credentials are streamed on stdin, never command-line parameters.
    {
      while read -r login group kind; do
        case "$kind" in
          API) password="$API_PASSWORD" ;;
          WORKER) password="$WORKER_PASSWORD" ;;
          WEBHOOK) password="$WEBHOOK_PASSWORD" ;;
          *) exit 2 ;;
        esac
        [[ "$login" =~ ^[a-z_]+$ && "$group" =~ ^[a-z_]+$ ]] || exit 2
        printf "DO \$ads\$ BEGIN IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='%s') THEN CREATE ROLE %s LOGIN INHERIT NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE PASSWORD '%s'; ELSE ALTER ROLE %s LOGIN INHERIT NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE PASSWORD '%s'; END IF; END \$ads\$;\n" \
          "$login" "$login" "$password" "$login" "$password"
        printf 'GRANT %s TO %s;\n' "$group" "$login"
        printf 'GRANT CONNECT ON DATABASE %s TO %s;\n' "$database" "$login"
      done < <(roles_for "$app")
    } | docker exec -i "$container" psql -X -q -U "$owner" -d "$database" -v ON_ERROR_STOP=1 >/dev/null
  fi
  while read -r login group kind; do
    verify_role "$container" "$owner" "$login" "$group"
  done < <(roles_for "$app")
  if [[ "$mode" == --provision ]]; then
    [[ ! -L "$connections" ]] || exit 2
    tmp="$(mktemp "$dir/.connections-$app-XXXXXXXX")"
    case "$app" in
      education)
        printf 'DATABASE_URL=postgresql://ads_education_api:%s@%s:5432/%s\n' "$API_PASSWORD" "$container" "$database"
        printf 'EDU_WORKER_DATABASE_URL=postgresql://ads_education_worker:%s@%s:5432/%s\n' "$WORKER_PASSWORD" "$container" "$database"
        printf 'EDU_WEBHOOK_DATABASE_URL=postgresql://ads_education_webhook:%s@%s:5432/%s\n' "$WEBHOOK_PASSWORD" "$container" "$database"
        ;;
      fleetguard)
        printf 'DATABASE_URL=postgresql://ads_fleetguard_api:%s@%s:5432/%s\n' "$API_PASSWORD" "$container" "$database"
        ;;
      mamacare)
        printf 'DATABASE_URL=postgresql://ads_mamacare_api:%s@%s:5432/%s\n' "$API_PASSWORD" "$container" "$database"
        printf 'MAMACARE_JOB_DATABASE_URL=postgresql://ads_mamacare_worker:%s@%s:5432/%s\n' "$WORKER_PASSWORD" "$container" "$database"
        ;;
      tontine)
        printf 'DATABASE_URL=postgresql://tontine_api:%s@%s:5432/%s\n' "$API_PASSWORD" "$container" "$database"
        printf 'TONTINE_WORKER_DATABASE_URL=postgresql://tontine_worker:%s@%s:5432/%s\n' "$WORKER_PASSWORD" "$container" "$database"
        printf 'TONTINE_WEBHOOK_DATABASE_URL=postgresql://tontine_webhook:%s@%s:5432/%s\n' "$WEBHOOK_PASSWORD" "$container" "$database"
        ;;
    esac > "$tmp"
    chmod 0600 "$tmp"
    mv -f -- "$tmp" "$connections"
  else
    safe_file "$connections" || { echo "MISSING_APP_CONNECTIONS app=$app" >&2; exit 1; }
  fi
  echo "APP_RUNTIME_READY app=$app"
  unset API_PASSWORD WORKER_PASSWORD WEBHOOK_PASSWORD POSTGRES_PASSWORD
done
echo 'ADS_FIVE_RESTRICTED_RUNTIME_LOGINS=PASS'
echo 'MAMACARE_JOB_POOL=REQUIRES_APP_CHANGE; APPS=NOT_STARTED; HTTPS=NOT_PUBLISHED'
